"""Human-readable Markdown report."""

from __future__ import annotations

from datetime import datetime, timezone
from typing import TYPE_CHECKING

from sparkmedic.analysis.knowledge import DOCS_REVIEWED
from sparkmedic.units import fmt_bytes, fmt_ms, fmt_pct
from sparkmedic.version import __version__

if TYPE_CHECKING:  # pragma: no cover
    from sparkmedic.analysis.engine import Diagnosis

_BADGE = {"critical": "CRITICAL", "high": "HIGH", "medium": "MEDIUM", "low": "LOW", "info": "INFO"}


def _ts(ms) -> str:
    if not ms:
        return "n/a"
    return datetime.fromtimestamp(ms / 1000, tz=timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def render_markdown(d: "Diagnosis") -> str:
    o = d.overview
    snap = d.snapshot
    lines: list[str] = []
    add = lines.append
    add(f"# Spark performance diagnosis: {snap.app_name or snap.app_id}")
    add("")
    add(f"_Generated by sparkmedic {__version__} on {_ts(d.generated_at_ms)}. "
        f"Recommendations reference Apache Spark and Databricks docs reviewed {DOCS_REVIEWED}._")
    add("")

    # ---- summary
    add("## Summary")
    add("")
    status = "completed" if o["completed"] else "running / incomplete"
    add(f"- **Application:** `{snap.app_id}` ({status}), Spark {o['spark_version'] or 'unknown'}")
    add(f"- **Source:** {o['source']['kind']} `{o['source']['target']}`" + (f" ({o['source']['detail']})" if o['source']['detail'] else ""))
    add(f"- **Duration:** {fmt_ms(o['duration_ms'])}; total task time {fmt_ms(o['total_task_time_ms'])}")
    cl = o.get("cluster") or {}
    cluster_bits = [f"{o['total_cores']} cores across {o['executors']} executor(s)"]
    if cl.get("node_type"):
        cluster_bits.append(f"workers {cl['node_type']}")
    if cl.get("spark_version"):
        cluster_bits.append(f"runtime {cl['spark_version']}")
    if o.get("photon") is not None:
        cluster_bits.append("Photon on" if o["photon"] else "Photon off")
    add(f"- **Cluster:** {', '.join(cluster_bits)}")
    if o.get("cluster_utilization") is not None:
        add(f"- **Core utilization:** {fmt_pct(o['cluster_utilization'])} of available core-time was spent running tasks")
    add(f"- **Work:** {o['jobs']} jobs, {o['stages']} stages, {o['sql_executions']} SQL queries, {o['failed_tasks']} failed tasks")
    add("")

    if not d.findings:
        add("No significant performance problems were found with the current thresholds.")
        add("")
    else:
        add("### Top issues")
        add("")
        for i, f in enumerate(d.findings[:5], 1):
            share = f" (involves {fmt_pct(f.impact_share)} of total task time)" if f.impact_share else ""
            add(f"{i}. **[{_BADGE[f.severity]}]** {f.title}{share}")
        add("")

    # ---- findings
    if d.findings:
        add("## Findings and fixes")
        add("")
    for i, f in enumerate(d.findings, 1):
        add(f"### {i}. [{_BADGE[f.severity]}] {f.title}")
        add("")
        meta = [f"rule `{f.rule_id}`", f"category {f.category}", f"confidence {f.confidence}"]
        if f.stage_ids:
            meta.append("stages " + ", ".join(map(str, f.stage_ids[:10])))
        if f.sql_ids:
            meta.append("SQL queries " + ", ".join(map(str, f.sql_ids[:10])))
        add(f"_{'; '.join(meta)}_")
        add("")
        add(f.summary)
        add("")
        if f.evidence:
            add("**What the metrics show**")
            add("")
            for e in f.evidence:
                add(f"- {e}")
            add("")
        if f.root_cause:
            add("**Why it is slow**")
            add("")
            add(f.root_cause)
            add("")
        if f.recommendations:
            add("**What to do**")
            add("")
            for j, r in enumerate(f.recommendations, 1):
                add(f"{j}. _{r.kind}_: **{r.title}**" + (f". {r.detail}" if r.detail else ""))
                if r.snippet:
                    add("")
                    add(f"   ```{r.language or 'text'}")
                    for ln in r.snippet.splitlines():
                        add(f"   {ln}")
                    add("   ```")
            add("")
        if f.references:
            add("**References:** " + "; ".join(f"[{r.title}]({r.url})" for r in f.references))
            add("")

    # ---- stage table
    if o["top_stages"]:
        add("## Longest stages")
        add("")
        add("| Stage | Share | Task time | Wall | Tasks | Input | Shuffle read | Shuffle write | Disk spill | GC | Max/median |")
        add("|---|---|---|---|---|---|---|---|---|---|---|")
        for s in o["top_stages"]:
            mom = f"{s['max_over_median']:.1f}x" if s.get("max_over_median") else "n/a"
            add(
                f"| {s['stage_id']} | {fmt_pct(s['share'])} | {fmt_ms(s['task_time_ms'])} | {fmt_ms(s['wall_time_ms'])} | "
                f"{s['num_tasks']:,} | {fmt_bytes(s['input_bytes'])} | {fmt_bytes(s['shuffle_read_bytes'])} | "
                f"{fmt_bytes(s['shuffle_write_bytes'])} | {fmt_bytes(s['spill_disk_bytes'])} | {fmt_pct(s['gc_ratio'])} | {mom} |"
            )
        add("")
    if o["top_sql"]:
        add("## Longest SQL queries")
        add("")
        for q in o["top_sql"]:
            add(f"- Query {q['execution_id']}: {fmt_ms(q['duration_ms'])}, {fmt_pct(q['share'])} of task time, "
                f"{q['status']} (`{q['description'][:90]}`)")
        add("")

    notes = list(snap.notes) + [f"Rule error: {e}" for e in d.errors]
    if notes:
        add("## Data collection notes")
        add("")
        for n in notes:
            add(f"- {n}")
        add("")

    add("## Confirm before acting")
    add("")
    add("Please check that this diagnosis matches what you want to fix:")
    add("")
    add("1. Is the slow part you care about among the stages or queries listed above? If not, rerun with "
        "`--focus-stage <id>` or `--focus-sql <id>`.")
    add("2. Was this run representative (normal data volume, cluster size and configuration)?")
    add("3. Do the proposed changes keep your results the same? Test code changes on a sample and compare outputs "
        "(for example with `exceptAll`) before rolling them out.")
    add("")
    return "\n".join(lines)
